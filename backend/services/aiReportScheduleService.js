const pool = require('../config/db');
const { buildReport } = require('./aiReportService');
const { sendEmail } = require('./emailService');

let timer;
let running = false;

function nextRun(from, frequency) {
    const next = new Date(from);
    if (frequency === 'Weekly') next.setUTCDate(next.getUTCDate() + 7);
    if (frequency === 'Monthly') next.setUTCMonth(next.getUTCMonth() + 1);
    if (frequency === 'Quarterly') next.setUTCMonth(next.getUTCMonth() + 3);
    return next;
}

async function run() {
    if (running) return;
    running = true;
    try {
        const schedules = (await pool.query(
            `SELECT s.*,u.email creator_email,u.role creator_role
             FROM ai_report_schedules s
             JOIN users u ON u.id=s.created_by AND u.status='Active'
             WHERE s.enabled=TRUE AND s.next_run_at<=NOW()
             ORDER BY s.next_run_at LIMIT 20`
        )).rows;
        for (const schedule of schedules) {
            const client = await pool.connect();
            try {
                await client.query('BEGIN');
                const locked = (await client.query(
                    `SELECT * FROM ai_report_schedules WHERE id=$1 AND enabled=TRUE AND next_run_at<=NOW() FOR UPDATE SKIP LOCKED`,
                    [schedule.id]
                )).rows[0];
                if (!locked) {
                    await client.query('ROLLBACK');
                    continue;
                }
                const today = new Date().toISOString().slice(0, 10);
                const report = await buildReport({
                    reportType: schedule.report_type,
                    division: schedule.division,
                    periodEnd: today
                }, client);
                const snapshot = (await client.query(
                    `INSERT INTO ai_report_snapshots(
                        report_type,division,period_end,status,report_data,commentary,created_by,finalised_by,finalised_at
                     ) VALUES($1,$2,$3,'Finalised',$4,'Automatically generated by the approved report schedule.',$5,$5,NOW())
                     RETURNING id`,
                    [schedule.report_type, schedule.division, today, report, schedule.created_by]
                )).rows[0];
                await client.query(
                    `UPDATE ai_report_schedules SET last_run_at=NOW(),next_run_at=$1,updated_at=NOW() WHERE id=$2`,
                    [nextRun(schedule.next_run_at, schedule.frequency), schedule.id]
                );
                await client.query(
                    `INSERT INTO audit_logs(user_id,user_email,user_role,action,entity_type,entity_id,status,details)
                     VALUES($1,$2,$3,'AI_REPORT_SCHEDULE_EXECUTED','AIReport',$4,'Success',$5)`,
                    [schedule.created_by, schedule.creator_email, schedule.creator_role, String(snapshot.id), {
                        scheduleId: schedule.id,
                        reportType: schedule.report_type,
                        division: schedule.division,
                        riskCount: report.summary.total_risks
                    }]
                );
                await client.query('COMMIT');
                if (schedule.recipient_email) {
                    await sendEmail({
                        to: schedule.recipient_email,
                        subject: `NCA GRC scheduled report: ${report.title}`,
                        text: `${report.title}\n\n${report.narrative}\n\nVersion ${snapshot.id} is available in the secured Reports workspace.`,
                        html: `<h2>${escapeHtml(report.title)}</h2><p>${escapeHtml(report.narrative)}</p><p>Governed report version ${snapshot.id} is available in the secured NCA GRC Reports workspace.</p>`,
                        emailType: 'Scheduled Governed AI Report',
                        userId: schedule.created_by,
                        role: schedule.creator_role,
                        directorate: schedule.division,
                        sentBy: schedule.created_by
                    });
                }
            } catch (error) {
                await client.query('ROLLBACK').catch(() => {});
                console.error('[aiReportScheduleService]', error.message);
            } finally {
                client.release();
            }
        }
    } catch (error) {
        if (error.code !== '42P01') console.error('[aiReportScheduleService]', error.message);
    } finally {
        running = false;
    }
}

function start() {
    if (timer) return;
    timer = setInterval(run, 60 * 1000);
    timer.unref?.();
    setTimeout(run, 8000);
}

function escapeHtml(value) {
    return String(value || '').replace(/[&<>"']/g, character => ({
        '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
    }[character]));
}

module.exports = { start, run, nextRun };
