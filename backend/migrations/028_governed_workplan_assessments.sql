UPDATE workplan_risk_assessments
SET system_likelihood = COALESCE(system_likelihood, likelihood),
    system_impact = COALESCE(system_impact, impact),
    system_score = COALESCE(system_score, risk_score),
    system_level = COALESCE(system_level, risk_level),
    system_response = COALESCE(system_response, risk_response),
    assessment_explanation = COALESCE(
        assessment_explanation,
        'Legacy system assessment: likelihood ' || likelihood || ' x impact ' || impact ||
        ' = ' || risk_score || ' (' || risk_level || '), response ' || risk_response || '.'
    );

CREATE INDEX IF NOT EXISTS idx_workplan_assessments_final_learning
    ON workplan_risk_assessments (risk_category, chairman_at DESC)
    WHERE chairman_at IS NOT NULL;

COMMENT ON COLUMN workplan_risk_assessments.system_score IS
    'Immutable score generated by the governed rules at upload time.';
COMMENT ON COLUMN workplan_risk_assessments.focal_score IS
    'Automatically calculated score proposed by the Risk Focal Person; never replaces the system baseline.';
COMMENT ON COLUMN workplan_risk_assessments.chairman_score IS
    'Final approved score used as a governed historical learning example.';
